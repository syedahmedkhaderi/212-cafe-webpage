// Turns src/lib/copy.json into supabase/migrations/0008_content_seed.sql.
//
//   node data/generate-content-seed.mjs
//
// site_content is seeded FROM the compiled dictionary rather than typed out again, so
// the database and the fallback the app uses when a key is missing cannot drift apart.
// Idempotent: `on conflict do nothing`, so re-running never overwrites an edit the owner
// has already made through /admin/content.
import fs from 'fs';
import path from 'path';
import url from 'url';

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const copy = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/lib/copy.json'), 'utf8'));

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

/**
 * Which admin section each key belongs to, by key prefix. Order matters — first match
 * wins — so `heroLocation` lands in "hero" rather than in the catch-all.
 */
const GROUPS = [
  [/^hero/, 'hero', 10],
  [/^view/, 'view', 20],
  [/^signatures?/, 'signatures', 30],
  [/^menu/, 'menu', 40],
  [/^visit|^hours|^getDirections|^closed/, 'visit', 50],
  [/^footer/, 'footer', 60],
  [/^nav|^brand|^full|^open|^close|^back/, 'navigation', 70],
  [/^language|^choose|^switch/, 'language', 80],
];

const groupFor = (key) => {
  for (const [re, name, base] of GROUPS) if (re.test(key)) return { name, base };
  return { name: 'general', base: 90 };
};

const rows = Object.entries(copy).map(([key, value], i) => {
  const { name, base } = groupFor(key);
  return { key, en: value.en, ar: value.ar, group: name, sort: base * 100 + i };
});

rows.sort((a, b) => a.sort - b.sort);

const sql = `-- 212 Café — editable copy, seeded from the compiled dictionary
--
-- GENERATED by data/generate-content-seed.mjs from src/lib/copy.json. Do not hand-edit:
-- regenerate it instead, or the database and the app's fallback will disagree about what
-- the default copy is.
--
-- \`on conflict do nothing\` on purpose. This runs on every fresh clone, and must never
-- overwrite copy the owner has already changed through /admin/content.

begin;

insert into site_content (key, value_en, value_ar, kind, group_name, sort_order) values
${rows
  .map((r) => `  (${q(r.key)}, ${q(r.en)}, ${q(r.ar)}, 'text', ${q(r.group)}, ${r.sort})`)
  .join(',\n')}
on conflict (key) do nothing;

commit;
`;

const out = path.join(ROOT, 'supabase/migrations/0008_content_seed.sql');
fs.writeFileSync(out, sql);

const byGroup = rows.reduce((acc, r) => ((acc[r.group] = (acc[r.group] ?? 0) + 1), acc), {});
console.log(`wrote ${rows.length} copy rows to ${path.relative(ROOT, out)}`);
for (const [g, n] of Object.entries(byGroup)) console.log(`  ${g.padEnd(14)} ${n}`);
