// Transforms the crawled menu.json into supabase/migrations/0003_seed.sql.
// Re-runnable: the SQL uses source_id upserts, so re-seeding never duplicates rows.
import fs from 'fs';
import path from 'path';

const DATA = '/Users/syed/Downloads/212-cafe/data';
const OUT = '/Users/syed/Downloads/212-cafe/supabase/migrations/0003_seed.sql';

const items = JSON.parse(fs.readFileSync(path.join(DATA, 'menu.json'), 'utf8'));
const manifest = JSON.parse(fs.readFileSync(path.join(DATA, 'images-manifest.json'), 'utf8'));
const fileBySourceId = new Map(manifest.filter((m) => m.file).map((m) => [m.id, m.file]));

const q = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// These three are not dishes. On the incumbent they are add-ons masquerading as
// products because that POS has no modifier concept. They become modifier options.
const ADDON_SOURCE_NAMES = new Set(['Extra Milk -', 'Extra Milk', 'Extras']);

const SIGNATURE = new Set([
  '212-Signature', 'the 3 Layers', 'Eggs Benedict', 'The French Toast', 'Brownies Chocolate Bomb',
]);

// Real add-on prices lifted from their own menu, so these are not invented.
const addonPrice = (name) => {
  const hit = items.find((i) => i.name_en === name);
  return hit ? hit.price : null;
};
const EXTRA_MILK = addonPrice('Extra Milk -') ?? 3;
const EXTRA_PORTION = addonPrice('Extras') ?? 10;

const sellable = items.filter((i) => !ADDON_SOURCE_NAMES.has(i.name_en));

// Categories, ordered by their source id (the café's own ordering).
const cats = [];
for (const i of sellable) {
  if (!cats.some((c) => c.id === i.category_id)) {
    cats.push({ id: i.category_id, name: i.category });
  }
}
cats.sort((a, b) => a.id - b.id);

const ARABIC_CATEGORY = {
  'Hot Beverage': 'مشروبات ساخنة',
  'Cold Beverage': 'مشروبات باردة',
  'Sweets-Pastry': 'حلويات ومعجنات',
  'Savoury': 'مأكولات',
  'Brunch': 'فطور متأخر',
  'Salads': 'سلطات',
};

let sql = `-- 212 Café — seed data
--
-- Generated by data/generate-seed.mjs from data/menu.json, crawled 2026-08-26 from
-- 212.smaresto.com/selforder/api/products. Item names, Arabic names, descriptions and
-- prices are the café's REAL data — none of it is invented.
--
-- Two deliberate departures from the source, both documented in data/FINDINGS.md:
--   1. "Extra Milk -", "Extra Milk" and "Extras" are excluded as products. They are
--      add-ons that only exist as separate line items because the incumbent POS has no
--      modifier support. They are re-created below as modifier options at their real
--      prices (QAR ${EXTRA_MILK} and QAR ${EXTRA_PORTION}).
--   2. Modifier prices marked "UNCONFIRMED" have no counterpart in the source data.
--      They are proposals and MUST be confirmed with the owner before the demo is
--      presented as a quote.
--
-- Re-runnable: upserts key on source_id.

begin;

-- --------------------------------------------------------------- settings

insert into business_settings (id, latitude, longitude)
values (1, 25.368100, 51.527700)
on conflict (id) do nothing;

-- Hours per their Instagram (12:00–00:00 daily). Google shows ~12:30–23:00, so these
-- need confirming — which is exactly why they are editable rows, not frontend constants.
insert into business_hours (day_of_week, opens_at, closes_at, is_closed) values
  (0, '12:00', '00:00', false),
  (1, '12:00', '00:00', false),
  (2, '12:00', '00:00', false),
  (3, '12:00', '00:00', false),
  (4, '12:00', '00:00', false),
  (5, '12:00', '00:00', false),
  (6, '12:00', '00:00', false)
on conflict (day_of_week) do nothing;

-- ------------------------------------------------------------- categories

insert into menu_categories (source_id, name_en, name_ar, slug, sort_order) values
`;

sql += cats
  .map((c, n) => `  (${c.id}, ${q(c.name)}, ${q(ARABIC_CATEGORY[c.name] || '')}, ${q(slugify(c.name))}, ${n * 10})`)
  .join(',\n');
sql += `
on conflict (source_id) do update set
  name_en = excluded.name_en, name_ar = excluded.name_ar, sort_order = excluded.sort_order;

-- ------------------------------------------------------------------ items
-- ${sellable.length} sellable items across ${cats.length} categories.

insert into menu_items
  (source_id, category_id, sku, name_en, name_ar, description_en, description_ar,
   price, image_path, is_available, is_signature, sort_order)
values
`;

const rows = [];
let order = 0;
for (const c of cats) {
  for (const i of sellable.filter((x) => x.category_id === c.id)) {
    const file = fileBySourceId.get(i.id);
    rows.push(
      `  (${i.id}, (select id from menu_categories where source_id = ${c.id}), ${q(i.sku)}, ` +
      `${q(i.name_en)}, ${q(i.name_ar)}, ${q(i.desc_en)}, ${q(i.desc_ar)}, ` +
      `${i.price.toFixed(2)}, ${file ? q('/menu/' + file.replace(/\.[^.]+$/, '.webp')) : 'null'}, ${i.active}, ` +
      `${SIGNATURE.has(i.name_en)}, ${(order += 10)})`
    );
  }
}
sql += rows.join(',\n');
sql += `
on conflict (source_id) do update set
  category_id    = excluded.category_id,
  name_en        = excluded.name_en,
  name_ar        = excluded.name_ar,
  description_en = excluded.description_en,
  description_ar = excluded.description_ar,
  price          = excluded.price,
  image_path     = excluded.image_path,
  is_available   = excluded.is_available,
  is_signature   = excluded.is_signature,
  sort_order     = excluded.sort_order;

-- -------------------------------------------------------------- modifiers
--
-- The incumbent has none of this. Prices sourced from their own add-on products where
-- one exists; everything marked UNCONFIRMED is a proposal awaiting the owner's sign-off.

insert into menu_item_modifier_groups (id, name_en, name_ar, min_select, max_select, sort_order) values
  ('11111111-1111-4111-8111-000000000001', 'Milk',       'الحليب',      1, 1, 10),
  ('11111111-1111-4111-8111-000000000002', 'Size',       'الحجم',       1, 1, 20),
  ('11111111-1111-4111-8111-000000000003', 'Extras',     'إضافات',      0, 4, 30),
  ('11111111-1111-4111-8111-000000000004', 'Add to dish','إضافة للطبق', 0, 3, 40)
on conflict (id) do nothing;

insert into menu_item_modifier_options (group_id, name_en, name_ar, price_delta, is_default, sort_order) values
  -- Milk: the QAR ${EXTRA_MILK} delta is their real "Extra Milk" price.
  ('11111111-1111-4111-8111-000000000001', 'Whole milk',   'حليب كامل الدسم', 0,               true,  10),
  ('11111111-1111-4111-8111-000000000001', 'Skimmed milk', 'حليب خالي الدسم', 0,               false, 20),
  ('11111111-1111-4111-8111-000000000001', 'Oat milk',     'حليب الشوفان',    ${EXTRA_MILK.toFixed(2)}, false, 30),
  ('11111111-1111-4111-8111-000000000001', 'Almond milk',  'حليب اللوز',      ${EXTRA_MILK.toFixed(2)}, false, 40),
  -- Size: UNCONFIRMED — no size data exists in the source menu.
  ('11111111-1111-4111-8111-000000000002', 'Regular', 'عادي', 0,    true,  10),
  ('11111111-1111-4111-8111-000000000002', 'Large',   'كبير', 6.00, false, 20),
  -- Drink extras: extra shot / syrup are UNCONFIRMED proposals.
  ('11111111-1111-4111-8111-000000000003', 'Extra espresso shot', 'شوت إسبريسو إضافي', 6.00, false, 10),
  ('11111111-1111-4111-8111-000000000003', 'Vanilla syrup',       'صوص الفانيليا',     3.00, false, 20),
  ('11111111-1111-4111-8111-000000000003', 'Caramel syrup',       'صوص الكراميل',      3.00, false, 30),
  ('11111111-1111-4111-8111-000000000003', 'Decaf',               'خالي الكافيين',     0,    false, 40),
  -- Food add-on priced from their real "Extras" product (QAR ${EXTRA_PORTION}).
  ('11111111-1111-4111-8111-000000000004', 'Extra portion', 'حصة إضافية', ${EXTRA_PORTION.toFixed(2)}, false, 10),
  ('11111111-1111-4111-8111-000000000004', 'Add avocado',   'إضافة أفوكادو', ${EXTRA_PORTION.toFixed(2)}, false, 20)
on conflict do nothing;

-- Attach Milk/Size/Extras to milk-based and brewed drinks only; espresso-only and
-- non-coffee items are deliberately excluded.
insert into menu_item_modifier_links (item_id, group_id, sort_order)
select mi.id, g.id, g.sort_order
from menu_items mi
cross join menu_item_modifier_groups g
join menu_categories mc on mc.id = mi.category_id
where g.id in (
        '11111111-1111-4111-8111-000000000001',
        '11111111-1111-4111-8111-000000000002',
        '11111111-1111-4111-8111-000000000003')
  and mc.name_en in ('Hot Beverage', 'Cold Beverage')
  and mi.name_en not in ('Normal water', 'Sparkling water', 'Fresh Orange Juice')
on conflict do nothing;

insert into menu_item_modifier_links (item_id, group_id, sort_order)
select mi.id, '11111111-1111-4111-8111-000000000004', 40
from menu_items mi
join menu_categories mc on mc.id = mi.category_id
where mc.name_en in ('Brunch', 'Salads', 'Savoury')
on conflict do nothing;

-- ----------------------------------------------------------------- tables
-- 12 tables. The incumbent's QR carried ?table_id=12, so 12 keeps the demo familiar.

insert into cafe_tables (label, seats, sort_order)
select lpad(n::text, 2, '0'), case when n % 4 = 0 then 4 else 2 end, n * 10
from generate_series(1, 12) as n
on conflict (label) do nothing;

-- One active opaque token per table. 128 bits of entropy, revocable — the fix for ?table_id=12.
insert into table_qr_tokens (table_id)
select t.id from cafe_tables t
where not exists (
  select 1 from table_qr_tokens q where q.table_id = t.id and q.is_active
);

commit;
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, sql);

console.log(`wrote ${OUT}`);
console.log(`categories=${cats.length} sellable_items=${sellable.length} excluded_addons=${items.length - sellable.length}`);
console.log(`images_linked=${rows.filter((r) => r.includes("'menu/")).length}`);
console.log(`addon prices from source: extra milk=${EXTRA_MILK} extras=${EXTRA_PORTION}`);
